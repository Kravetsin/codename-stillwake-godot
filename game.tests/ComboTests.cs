using Stillwake.Game.Features.Crew;
using Xunit;

namespace Stillwake.Game.Tests;

/// <summary>The fire axe's combo (axe-combos): the picked motion sample by sample, and the arm and the body never jumping.</summary>
public class ComboTests
{
    /// <summary>How finely the clock is driven: every golden time falls on a frame.</summary>
    private const double Tick = 0.25;

    private static readonly double Down40 = 40 * Math.PI / 180, Up20 = -20 * Math.PI / 180;

    /// <summary>
    /// Held from rest for <paramref name="ms"/>, aimed by <paramref name="aimAt"/> at each moment, in <see cref="Tick"/> frames:
    /// at each frame's time, the play and how far into it.
    /// </summary>
    private static List<(double At, MotionPlay Play, double Ms)> Held(double ms, Func<double, double> aimAt, Func<double, bool>? wanted = null)
    {
        var swing = new AxeSwing();
        var played = new List<(double, MotionPlay, double)>();
        for (int i = 0; i * Tick <= ms; i++)
        {
            double at = i * Tick;
            swing.Advance(Tick, wanted?.Invoke(at) ?? true, angle: aimAt(at));
            if (swing.Phase is double phase) played.Add((at, swing.Play!, phase * swing.Play!.Ms));
        }
        return played;
    }

    /// <summary>The aims of the golden's jumping run: each step its own, by its time in the cycle.</summary>
    private static double Jumping(double at) => (at % 1500) switch { < 450 => 0, < 900 => Down40, _ => Up20 };

    /// <summary>
    /// The drawn arm and body against combos.js's card l3 held, the blade biting at every hit, sampled in its second cycle
    /// (the first begins from rest, the page's from step 3's end): t, s, e, w, angle, lean, dip, shift, front, front lift, back,
    /// back lift, far upper, far lower, grip, each within 0.01.
    /// </summary>
    [Theory]
    [InlineData("straight")]
    [InlineData("low")]
    [InlineData("jump")]
    public void HeldItPlaysThePickedMotionSampleBySample(string mode)
    {
        var (rows, aim) = mode switch
        {
            "straight" => (Straight, (Func<double, double>)(_ => 0)),
            "low" => (Low, _ => Down40),
            _ => (Jump, Jumping),
        };
        var played = Held(3000, aim).ToDictionary(p => p.At);
        Assert.Equal(0.717758, MotionPlay.Of(Strokes.Axe, 0, 0).Lead, 5);
        foreach (var row in rows)
        {
            var (_, play, ms) = played[1500 + row[0]];
            double shown = AxeSwing.Shown(ms / play.Ms, play), angle = play.AngleAt(play.Aim, shown);
            double elbow = play.ElbowAt(shown), wrist = play.WristAt(shown);
            var body = ComboBody.At(play, ms)!.Value;
            var (farU, farE) = (body.FarArm, body.FarElbow);
            if (body.Grip > 0)
            {
                var hold = HaftGrip.ArmFor(AxeSwing.ArmAt(angle, elbow), HeldLook.FireAxe, wrist).Arm;
                (farU, farE) = (farU + (hold.Upper - farU) * body.Grip, farE + (hold.Lower - farE) * body.Grip);
            }
            double[] got = [row[0], angle - play.Aim - play.Lead, elbow, wrist, angle, body.Lean, body.Dip, (body.Front + body.Back) / 2 + body.Push,
                body.Front, body.FrontLift, body.Back, body.BackLift, farU, farE, body.Grip];
            for (int i = 1; i < row.Length; i++)
                Assert.True(Math.Abs(got[i] - row[i]) < 0.01, $"{mode} at {row[0]} ms, column {i}: {got[i]:F4}, wanted {row[i]}");
        }
    }

    [Fact]
    public void HeldItStrikesOnItsAimWithEveryStep()
    {
        foreach (var at in new[] { 204.75, 630, 1212 })
        {
            var (_, play, ms) = Held(1500 + at, Jumping).Last();
            Assert.Equal(play.HitShare!.Value * play.Ms, ms, 6);
            Assert.Equal(play.Aim + play.Lead, play.AngleAt(play.Aim, AxeSwing.Shown(ms / play.Ms, play)), 6);
        }
    }

    [Fact]
    public void TheArmNeverJumpsAcrossAStepOrAnAimChangedBetweenSteps()
    {
        var played = Held(3000, Jumping);
        var drawn = played.Select(p =>
        {
            double shown = AxeSwing.Shown(p.Ms / p.Play.Ms, p.Play);
            return (Turn: p.Play.AngleAt(p.Play.Aim, shown), Elbow: p.Play.ElbowAt(shown), Wrist: p.Play.WristAt(shown));
        }).ToList();
        Assert.Equal((int)(3000 / Tick) + 1, played.Count);
        for (int i = 1; i < drawn.Count; i++)
        {
            var (a, b) = (drawn[i - 1], drawn[i]);
            Assert.True(Math.Abs(a.Turn - b.Turn) < 0.05 && Math.Abs(a.Elbow - b.Elbow) < 0.05 && Math.Abs(a.Wrist - b.Wrist) < 0.05,
                $"at {played[i].At} ms: {a} to {b}");
        }
    }

    [Fact]
    public void TheBodyAndTheFeetNeverJumpThroughTwoHeldCyclesAndTheThirdStepEndsAtRest()
    {
        var bodies = Held(3000, _ => 0).Select(p => (p.At, Body: ComboBody.At(p.Play, p.Ms)!.Value)).ToList();
        for (int i = 1; i < bodies.Count; i++)
            Assert.True(bodies[i].Body.Near(bodies[i - 1].Body, 0.1), $"at {bodies[i].At} ms: {bodies[i - 1].Body} to {bodies[i].Body}");
        Assert.True(MotionPlay.Of(Strokes.Axe, 0, 2).EndsAtRest);
        Assert.False(MotionPlay.Of(Strokes.Axe, 0, 0).EndsAtRest);
        Assert.False(MotionPlay.Of(Strokes.Axe, 0, 1).EndsAtRest);
    }

    [Theory]
    [InlineData(0)]
    [InlineData(1)]
    public void LetGoTheBackBringsTheArmAndTheBodyToRestWithinItsTime(int after)
    {
        var step = MotionPlay.Of(Strokes.Axe, Down40, after);
        var back = MotionPlay.Back(step);
        Assert.Null(back.HitShare);
        Assert.Equal(Combos.BackMs, back.Ms);
        // It begins where the step left the arm and the body, and ends at rest on the line.
        Assert.Equal(step.SpliceAt(step.Ms).Arm, back.PoseAt(0));
        Assert.Equal(step.SpliceAt(step.Ms).Body, ComboBody.At(back, 0));
        Assert.True(back.EndsAtRest);
        var end = back.SpliceAt(Combos.BackMs);
        Assert.True(end.Body!.Value.Near(BodyState.Rest, 1e-9));
    }

