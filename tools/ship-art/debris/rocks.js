for (const [kind, more] of Object.entries(require('./rocks-more.js'))) ROCKS[kind].list.push(...more);

function drawRock(style, kind, i) {
  const K = ROCKS[kind], d = K.list[i], st = style, chunky = st.chunky;
  const p = new Pic(K.w, K.h, st, { seed: 11 + i * 31 + K.w });
  const craters = chunky ? d.craters.filter(c => c[2] >= 2.5).map(([x, y, r, k]) => [x, y, r * 1.1, k * 1.1]) : d.craters;
  const bumps = [...d.bumps, ...(chunky ? [] : d.pebbles.map(([x, y]) => [x, y, 1.6, 1.1]))];
  const s0 = st.rockBias; if (K.bias) st.rockBias += K.bias;
  rock(p, { pts: d.pts, R: d.R, craters, bumps, mat: K.mat, planes: d.planes });
  st.rockBias = s0;
  for (const c of d.cracks) crack(p, c, { w: chunky ? 2 : 1 });
  if (!chunky) for (const [x, y] of d.specks || []) if (p.has(x, y)) p.px(x, y, 'rust', Math.max(1, p.slotAt(x, y) - 1));
  for (const [v, w] of d.veins || []) vein(p, v, { w: chunky ? 2 : w });
  if (!chunky) for (const [x, y] of d.dust || []) if (p.has(x, y)) p.px(x, y, 'ore', Math.min(4, p.slotAt(x, y) + 1));
  for (const [x, y, s] of d.nuggets || []) nugget(p, x, y, chunky ? Math.max(3, s) : s);
  if (st.rockRim) p.rim([K.mat], { k: 5, min: 1 });
  for (const [x, y, r] of d.glints || []) glint(p, x, y, chunky ? Math.max(2, r) : r);
  p.name = `${kind}#${i + 1}`;
  return p;
}

module.exports = { ROCKS, drawRock };
