/** The pictures as images in the drawn ramps, named hd_head, hd_face_0-2, hd_hair_0-2. */
function pictures(A) {
  const keys = { ...A.FIXED };
  'LSDO'.split('').forEach((k, i) => (keys[k] = A.SKINS[A.SKIN_DRAWN][i]));
  '1234'.split('').forEach((k, i) => (keys[k] = A.HAIRS[A.HAIR_DRAWN][i]));
  const image = rows => {
    const img = { w: 26, h: 24, data: new Uint8ClampedArray(26 * 24 * 4) };
    rows.forEach((row, y) => [...row].forEach((k, x) => {
      if (k === '.' || k === ' ' || x >= 26) return;
      const [hex, a] = keys[k].split('/'), n = parseInt(hex.slice(1), 16);
      img.data.set([n >> 16, (n >> 8) & 255, n & 255, a ? +a : 255], (y * 26 + x) * 4);
    }));
    return img;
  };
  const out = { hd_head: image(head) };
  faces.forEach((f, i) => (out['hd_face_' + i] = image(f)));
  hairs.forEach((h, i) => (out['hd_hair_' + i] = image(h)));
  return out;
}

