// The breakers the game draws: their cut GPT pieces and a table of their bones, read from the rigs the pick page showed.
// node tools/pick-kit/pages/breaker-rigs/export.js
'use strict';
const fs = require('fs'), path = require('path');
const { spawnSync } = require('child_process');
require('./rig.js'); require('./rigs.js');
const ROOT = path.join(__dirname, '../../../..');
// the bodies in the game, and what each of their pictures swaps for
const GAME = [['knot', 'breakerKnot', 'BreakerKnot', { core: 'dead', open: 'shut' }]];

const png = f => fs.readFileSync(f);
function rgba(f) {
  const r = spawnSync('ffmpeg', ['-v', 'error', '-i', f, '-f', 'rawvideo', '-pix_fmt', 'rgba', '-'], { maxBuffer: 1 << 26 });
  if (r.status) throw new Error(String(r.stderr));
  return { w: png(f).readUInt32BE(16), h: png(f).readUInt32BE(20), d: r.stdout };
}
// the game reads a picture four times its size, so its sides grow right and down to a multiple of four
function save(f, im, keep) {
  const W = Math.ceil(im.w / 4) * 4, H = Math.ceil(im.h / 4) * 4, d = Buffer.alloc(W * H * 4);
  for (let y = 0; y < im.h; y++) for (let x = 0; x < im.w; x++) {
    const o = (y * im.w + x) * 4;
    if (!keep || keep(im.d[o], im.d[o + 1], im.d[o + 2])) im.d.copy(d, (y * W + x) * 4, o, o + 4);
  }
  const r = spawnSync('ffmpeg', ['-v', 'error', '-y', '-f', 'rawvideo', '-pix_fmt', 'rgba', '-s', `${W}x${H}`, '-i', '-', '-frames:v', '1', f], { input: d });
  if (r.status) throw new Error(String(r.stderr));
  return [W / 4, H / 4];
}
const n = (v, digits = 4) => String(+v.toFixed(digits)), f = v => n(v) + 'f';
let body = '';
for (const [id, game, name, swaps] of GAME) {
  const rig = globalThis.BreakerRig.ready(globalThis.RIGS[id]), src = path.join(__dirname, 'cut', id), cuts = JSON.parse(fs.readFileSync(path.join(src, 'cuts.json'), 'utf8'));
  const to = path.join(ROOT, 'game/art/hd/creatures', game), parts = [], sizes = [], index = new Map(rig.parts.map((p, i) => [p.id, i]));
  fs.mkdirSync(to, { recursive: true });
  const write = (part, pic, keep) => {
    const im = rgba(path.join(src, `${pic}_hd.png`)), [W, H] = save(path.join(to, `${part}.png`), im, keep), box = cuts[pic];
    const joint = (rig.joints && rig.joints[pic]) || rig.parts.find(p => p.pic === pic).pivot, per = im.w / 4 / box[2];
    parts.push(`            ["${part}"] = new(${W}, ${H}, ${f((joint[0] - box[0]) * per)}, ${f((joint[1] - box[1]) * per)}, []),`);
    sizes.push(`            ["${part}"] = ${n(rig.scale / per, 5)},`);
  };
  for (const pic of Object.keys(cuts)) write(pic, pic);
  // the lit slits alone, drawn over the core unlit
  write('lamp', 'core', (r, g, b) => r > 120 && g > 95 && g - b > 22 && r - g < 75);
  const bones = rig.parts.map(p => {
    if (p.flip) throw new Error(`${p.id}: the game's rig mirrors no part`);
    const up = p.parent === undefined ? -1 : index.get(p.parent), at = up < 0 ? p.at : [p.at[0] - rig.parts[up].pivot[0], p.at[1] - rig.parts[up].pivot[1]];
    return `            new("${p.id}", "${p.pic}", ${swaps[p.pic] ? `"${swaps[p.pic]}"` : 'null'}, ${up}, ${n(at[0])}, ${n(at[1])}, ${n(p.a || 0, 6)}, ${n(p.k || 1)}${p.pic === 'core' ? ', "lamp"' : ''}),`;
  });
  body += `
    /// <summary>«Клубок», the starting zone's breaker: GPT's painted pieces as they are, in <c>art/hd/creatures/${game}</c>.</summary>
    public static readonly BreakerDesign ${name} = new("${game}", ${n(rig.scale, 7)},
        new Dictionary<string, Part>
        {
${parts.join('\n')}
        },
        new Dictionary<string, double>
        {
${sizes.join('\n')}
        },
        [
${bones.join('\n')}
        ]);
`;
}
fs.writeFileSync(path.join(ROOT, 'game/Content/logic/BreakerInk.cs'), `// Generated by tools/pick-kit/pages/breaker-rigs/export.js: export again, never edit.
using System.Collections.Generic;

namespace Stillwake.Game;

public static partial class CreatureArt
{
    /// <summary>
    /// A breaker of painted pieces hung on joints: <paramref name="Scale"/> the world's pixels a pixel of its sheet, <paramref name="Sizes"/> what
    /// each picture is scaled by to stand at that, <paramref name="Bones"/> in draw order.
    /// </summary>
    public sealed record BreakerDesign(string Id, double Scale, IReadOnlyDictionary<string, Part> Parts, IReadOnlyDictionary<string, double> Sizes, BreakerBone[] Bones);

    /// <summary>
    /// A piece on its parent's joint (<paramref name="Parent"/>, none at -1), <paramref name="X"/> and <paramref name="Y"/> from it in the sheet's
    /// pixels; the picture it swaps for, and what shines over it while it is not swapped.
    /// </summary>
    public sealed record BreakerBone(string Id, string Picture, string? Swap, int Parent, double X, double Y, double A, double K, string? Shine = null);
${body}}
`);
console.log('exported');