// node tools/planet-art/creatures/export.js [artDir] [contentFile] — the creatures' looks the user picked on the loper page (ADR 0102):
// every part of each picked design as an index map (R ramp 23-31, G tone 0-5, A painted) and its glow map into
// <artDir>/creatures/<design>/, and their sizes, pivots, rig, pose numbers, eye and the palettes' ramps into the generated
// game/Content/logic/CreatureArt.cs, which the game recolours the maps by at load. Plain Node, no packages; deterministic.
const fs = require('fs'), path = require('path');
const L = require('./loper-parts.js'), PNG = require('../png.js');
const ROOT = path.join(__dirname, '..', '..', '..');
const ART = process.argv[2] || path.join(ROOT, 'game', 'art'), CS = process.argv[3] || path.join(ROOT, 'game', 'Content', 'CreatureArt.cs');
// The user's picks, 2026-10-22: «Пушок», «Тапирчик», «Шестиног», «Классика».
const PICKED = ['classic', 'tapir', 'sixleg'];

const glowing = (P) => P.role.some((r, q) => r === 'glow' && P.tone[q] >= 3);
function write(file, P, map) { const img = PNG.create(P.w, P.h); Buffer.from(map.buffer, map.byteOffset, map.length).copy(img.data); PNG.encode(img, file); }

const f = (v) => { const s = (Math.round(v * 1000) / 1000).toString(); return s.includes('.') ? s + 'f' : s; };
const str = (s) => JSON.stringify(s);
const cs = [];
cs.push('// Generated by tools/planet-art/creatures/export.js from the loper page\'s parts (ADR 0102): export again, never edit.');
cs.push('using System.Collections.Generic;', '', 'namespace Stillwake.Game;', '', 'public static partial class CreatureArt', '{');
cs.push('    /// <summary>Every picked design: its parts (<c>art/creatures/{design}/{part}</c>), its rig in drawing order, its pose numbers and its eye.</summary>');
cs.push('    public static readonly IReadOnlyDictionary<string, Design> Designs = new Dictionary<string, Design>', '    {');
for (const id of PICKED) {
  const d = L.DESIGNS.find((x) => x.id === id), b = L.build(d), dir = path.join(ART, 'creatures', id);
  fs.mkdirSync(dir, { recursive: true });
  const parts = [];
  for (const [name, P] of Object.entries(b.parts)) {
    write(path.join(dir, name + '.png'), P, L.indexMap(d, P));
    const glow = glowing(P);
    if (glow) { const m = L.indexMap(d, P); for (let q = 0; q < P.w * P.h; q++) if (P.role[q] !== 'glow' || P.tone[q] < 3) m[q * 4 + 3] = 0; write(path.join(dir, name + '_glow.png'), P, m); }
    const ramps = [...new Set(P.role.filter((r) => r))].map((r) => L.RAMP_INDEX[d.ramps[r] || r]);
    parts.push(`                [${str(name)}] = new(${P.w}, ${P.h}, ${-P.ox}, ${-P.oy}, [${ramps.join(', ')}]${glow ? ', Glow: true' : ''}),`);
  }
  const p = d.pose;
  cs.push(`        [${str(id)}] = new(${str(id)}, Gait.${d.gait[0].toUpperCase() + d.gait.slice(1)}, Headless: ${!!d.headless},`);
  cs.push(`            Glow: ${L.RAMP_INDEX[d.ramps.glow]},`);
  cs.push(`            Eye: new(${f(d.eye.at[0])}, ${f(d.eye.at[1])}, (${f(b.eye.travel[0])}, ${f(b.eye.travel[1])}), (${f(b.eye.travelWide[0])}, ${f(b.eye.travelWide[1])})),`);
  cs.push(`            Pose: new(EarUp: ${f(p.earUp)}, EarBack: ${f(p.earBack)}, EarPerk: ${f(p.earPerk)}, LegAmp: ${f(p.legAmp)}, Lift: ${f(p.lift)}, TailAmp: ${f(p.tailAmp)}, TailFlee: ${f(p.tailFlee)}, Graze: ${f(p.graze)}, Hop: ${f(p.hop || 0)}),`);
  cs.push('            Parts: new Dictionary<string, Part>', '            {', ...parts, '            },', '            Rig:', '            [');
  for (const n of d.rig) {
    const extra = [n.phase != null ? `Phase: ${f(n.phase)}` : '', n.hind ? 'Hind: true' : '', n.base ? `Base: ${f(n.base)}` : ''].filter(Boolean);
    cs.push(`                new(${str(n.id)}, ${str(n.part)}, ${n.parent ? str(n.parent) : 'null'}, ${f(n.at[0])}, ${f(n.at[1])}, ${n.drive ? 'Drive.' + n.drive[0].toUpperCase() + n.drive.slice(1) : 'Drive.None'}${extra.length ? ', ' + extra.join(', ') : ''}),`);
  }
  cs.push('            ]),');
  console.log(id, Object.keys(b.parts).length, 'parts');
}
cs.push('    };', '');
cs.push('    /// <summary>Each palette\'s ramps by index (the index maps\' R), six tones each, outline to highlight: a planet\'s creatures recoloured by one.</summary>');
cs.push('    public static readonly IReadOnlyDictionary<string, IReadOnlyDictionary<int, (byte R, byte G, byte B)[]>> Palettes = new Dictionary<string, IReadOnlyDictionary<int, (byte R, byte G, byte B)[]>>', '    {');
for (const [key, pal] of Object.entries(L.PALETTES)) {
  cs.push(`        [${str(key)}] = new Dictionary<int, (byte R, byte G, byte B)[]>`, '        {');
  for (const [role, ramp] of Object.entries(pal.ramps)) {
    const rgb = ramp.map((h) => `(${parseInt(h.slice(1, 3), 16)}, ${parseInt(h.slice(3, 5), 16)}, ${parseInt(h.slice(5, 7), 16)})`);
    cs.push(`            [${L.RAMP_INDEX[role]}] = [${rgb.join(', ')}],`);
  }
  cs.push('        },');
}
cs.push('    };', '}', '');
fs.writeFileSync(CS, cs.join('\n'));
console.log('wrote', path.relative(ROOT, CS));
