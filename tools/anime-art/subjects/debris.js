/** A truss between two points: two rails and their ties. */
function truss(a, x0, y0, x1, y1, w) {
  const L = Math.hypot(x1 - x0, y1 - y0), nx = (-(y1 - y0) / L) * (w / 2), ny = ((x1 - x0) / L) * (w / 2);
  a.shape(poly(x0 + nx, y0 + ny, x1 + nx, y1 + ny, x1 - nx, y1 - ny, x0 - nx, y0 - ny), SOOT, {});
  for (const s of [1, -1]) a.tube(`M${x0 + s * nx} ${y0 + s * ny}L${x1 + s * nx} ${y1 + s * ny}`, .9, OLD, { spec: false });
  const n = Math.round(L / 2.6);
  for (let i = 1; i < n; i++) { const t = i / n, q = i % 2 ? 1 : -1, xa = x0 + (x1 - x0) * t, ya = y0 + (y1 - y0) * t; a.line(`M${xa + q * nx} ${ya + q * ny}L${xa + (x1 - x0) / n - q * nx} ${ya + (y1 - y0) / n - q * ny}`, { w: .9, c: OLD.lite }); }
}
