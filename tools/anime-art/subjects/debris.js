  for (const t of [0, .25, .5, .75, 1]) { top.push([at(t), cy - R(t)]); foot.unshift([at(t), cy + R(t)]); }
  const d = o.outline ? outline(o.outline, o.seed) : poly(top.concat(foot).flat());
